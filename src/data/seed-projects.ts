/* ------------------------------------------------------------------
   Projects. One project serves exactly one building; a client with
   three buildings appears three times, which is exactly how the
   business signs and bills them.

   `deployed` is deliberately below `headcount` on several lines — an
   outsourcing company that reports 100% fulfilment every month is not
   reporting, it is guessing.
   ------------------------------------------------------------------ */

let seq = 0

/** Cost per person: take-home plus BPJS and the THR provision, rounded to the nearest thousand. */
const costOf = (base: number, allowance: number) => Math.round(((base + allowance) * 1.19) / 1000) * 1000

function R(
  positionId: string,
  headcount: number,
  deployed: number,
  shift: Shift,
  opts: { bill?: number; days?: number; hours?: number; note?: string } = {},
): ManpowerRequirement {
  const p = positions.find((x) => x.id === positionId)
  if (!p) throw new Error(`Unknown position ${positionId}`)
  seq += 1
  return {
    id: `req_${String(seq).padStart(3, '0')}`,
    positionId,
    headcount,
    deployed,
    shift,
    workDaysPerWeek: opts.days ?? 6,
    hoursPerShift: opts.hours ?? 8,
    billRate: opts.bill ?? p.defaultBillRate,
    costRate: costOf(p.baseSalary, p.allowance),
    note: opts.note,
  }
}

